def block(doc, text, align=WD_ALIGN_PARAGRAPH.RIGHT, bold=False, size=None):
    par = doc.add_paragraph()
    par.alignment = align
    par.paragraph_format.first_line_indent = Cm(0)
    par.paragraph_format.space_after = Pt(2)
    r = par.add_run(text)
    r.bold = bold
    if size:
        r.font.size = Pt(size)
    return par


