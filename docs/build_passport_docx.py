def rich(par, text):
    """Текст с [плейсхолдерами] — подсвечиваем их жёлтым."""
    import re
    for i, chunk in enumerate(re.split(r"(\[[^\]]*\])", text)):
        if not chunk:
            continue
        r = par.add_run(chunk)
        if i % 2 == 1:
            r.font.highlight_color = WD_COLOR_INDEX.YELLOW
    return par


def p(doc, text="", bold=False, align=None, indent=True, size=None):
    par = doc.add_paragraph()
    if not indent:
        par.paragraph_format.first_line_indent = Cm(0)
    if align is not None:
        par.alignment = align
    rich(par, text)
    for r in par.runs:
        if bold:
            r.bold = True
        if size:
            r.font.size = Pt(size)
    return par


def bullets(doc, items):
    for it in items:
        par = doc.add_paragraph(style="List Bullet")
        par.paragraph_format.first_line_indent = Cm(0)
        par.paragraph_format.line_spacing = 1.5
        par.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        rich(par, it)


def h(doc, text, level=1):
    return doc.add_heading(text, level=level)


def table(doc, rows, widths=None, header=True, size=12):
    t = doc.add_table(rows=0, cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, val in enumerate(row):
            cells[ci].text = ""
            par = cells[ci].paragraphs[0]
            par.paragraph_format.first_line_indent = Cm(0)
            par.paragraph_format.line_spacing = 1.0
            par.paragraph_format.space_after = Pt(2)
            rich(par, str(val))
            for r in par.runs:
                r.font.size = Pt(size)
                r.font.name = "Times New Roman"
                if header and ri == 0:
                    r.bold = True
    if widths:
        for ci, w in enumerate(widths):
            for row in t.rows:
                row.cells[ci].width = Cm(w)
    doc.add_paragraph()
    return t


def caption(doc, text, size=12):
    par = doc.add_paragraph()
    par.paragraph_format.first_line_indent = Cm(0)
    par.paragraph_format.space_after = Pt(4)
    par.alignment = WD_ALIGN_PARAGRAPH.LEFT
    rich(par, text)
    for r in par.runs:
        r.font.size = Pt(size)
        r.italic = True


def add_page_numbers(doc):
    """Номер страницы в нижнем колонтитуле по центру (поле PAGE)."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn

    par = doc.sections[0].footer.paragraphs[0]
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = par.add_run()
    run.font.size = Pt(12)
    run.font.name = "Times New Roman"
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    run._r.addnext(fld)


